// Executes the real invite/claim/recovery functions. PGlite lacks pgcrypto, so
// only its digest/random-byte primitives are shimmed using built-in SHA-256.
const fs = require('node:fs');
const assert = require('node:assert/strict');
const { PGlite } = require('@electric-sql/pglite');
const read = name => fs.readFileSync(`supabase/migrations/${name}`, 'utf8');
const migration = fs.readdirSync('supabase/migrations').find(n => n.endsWith('_supplier_delivery_recovery_p1.sql'));
const actor = '00000000-0000-4000-8000-000000000001';
const supplier = '00000000-0000-4000-8000-000000000002';
const request = '00000000-0000-4000-8000-000000000003';
(async () => {
  const db = new PGlite();
  try {
    await db.exec(`create role anon; create role authenticated; create role service_role bypassrls;
      create schema app_private; create schema auth; create schema extensions;
      create function auth.uid() returns uuid language sql as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
      create function extensions.digest(value text, algorithm text) returns bytea language sql as $$ select sha256(convert_to(value,'UTF8')) $$;
      create function extensions.gen_random_bytes(n int) returns bytea language sql as $$ select substring(sha256(convert_to(random()::text,'UTF8')) from 1 for n) $$;
      create table profiles(id uuid primary key,role text,is_active boolean,registration_status text);
      create table requests(id uuid primary key,created_by uuid,status text,category text,destination text,travel_date date,created_at timestamptz default now());
      create function app_private.account_is_active(uid uuid) returns boolean language sql as $$ select exists(select 1 from public.profiles where id=uid and is_active and registration_status='active') $$;
      create function app_private.first_uz_phone(phone text) returns text language sql as $$ select nullif(phone,'') $$;
      create function public.request_is_current(d date,c timestamptz) returns boolean language sql as $$ select d >= current_date $$;
      insert into profiles values('${actor}','agent',true,'active');
      insert into requests(id,created_by,status,category,travel_date) values('${request}','${actor}','open','Transfer',current_date+10);
      select set_config('request.jwt.claim.sub','${actor}',false);`);
    await db.exec(read('20261006123500_external_supplier_network.sql').split('create or replace function public.match_external_suppliers')[0]);
    await db.exec(read('20261010214000_p7_supplier_delivery_claim.sql'));
    await db.exec(read('20261024152200_supplier_email_bounce_suppression.sql'));
    await db.exec(read('20261025235613_supplier_invite_email_suppression_guard.sql'));
    await db.exec(read('20261026145058_recover_suppressed_supplier_invites.sql'));
    await db.exec(`insert into external_suppliers(id,supplier_type,name,email) values('${supplier}','transport','Fixture','a@example.com');
      insert into outreach_email_suppressions(email,reason,replacement_email) values('a@example.com','test','b@example.com');`);
    const create = async channel => (await db.query(`select create_supplier_invite($1,$2,$3) as result`,[request,supplier,channel])).rows[0].result;
    const row = async () => (await db.query('select * from supplier_invites')).rows[0];
    const first = await create('email'); // Legacy helper pre-resolves A -> B.
    assert.equal((await row()).suppressed_recipient, null);
    await db.exec(read(migration));
    assert.equal((await row()).suppressed_recipient,'a@example.com');
    await db.exec(`update outreach_email_suppressions set replacement_email='c@example.com' where email='a@example.com';`);
    assert.equal((await row()).recipient,'c@example.com','legacy recipient must follow a changed replacement');
    await create('email');
    assert.equal((await row()).suppressed_recipient,'a@example.com','real RPC must preserve original source');
    await db.exec(`update external_suppliers set email='new@example.com' where id='${supplier}';`);
    assert.equal((await row()).recipient,'new@example.com');
    await create('email');
    await db.exec(`update outreach_email_suppressions set replacement_email='obsolete@example.com' where email='a@example.com';`);
    assert.equal((await row()).recipient,'new@example.com','old suppression must not overwrite corrected supplier');
    assert.equal((await row()).suppressed_recipient,null);
    await db.exec(`update external_suppliers set email='a@example.com' where id='${supplier}';
      insert into outreach_email_suppressions(email,reason,replacement_email) values('obsolete@example.com','test','end@example.com');
      update outreach_email_suppressions set replacement_email='final@example.com' where email='obsolete@example.com';`);
    assert.equal((await row()).recipient,'final@example.com','intermediate chain edit must propagate');
    await db.exec(`insert into outreach_email_suppressions(email,reason,replacement_email) values('final@example.com','test','a@example.com');`);
    assert.equal((await row()).recipient,null,'cycles must fail closed');
    assert.equal((await row()).status,'failed');
    await db.exec(`delete from outreach_email_suppressions where email='final@example.com';`);
    assert.equal((await row()).recipient,'final@example.com');
    assert.equal((await row()).status,'failed','recovery never auto-queues');
    await db.exec(`update outreach_email_suppressions set replacement_email=null where email='a@example.com';`);
    await assert.rejects(create('email'),/supplier_email_suppressed/);
    await db.exec(`update outreach_email_suppressions set active=false where email='a@example.com';`);
    assert.equal((await row()).recipient,'a@example.com');

    // Use a real new SMS invite generation; uncertain attempts survive claim release
    // and expiry, and cannot be bypassed by recreating the invite/token.
    await db.exec(`update external_suppliers set phone='998901234567' where id='${supplier}';`);
    const sms = await create('sms');
    const claim = async token => (await db.query('select claim_supplier_invite_delivery($1,$2,$3) as result',[sms.invite_id,actor,token])).rows[0].result;
    await db.exec(`update external_suppliers set status='inactive' where id='${supplier}';`);
    assert.equal((await claim(sms.token)).status,'supplier_unavailable');
    await db.exec(`update external_suppliers set status='registry' where id='${supplier}';`);
    let delivery = await claim(sms.token);
    assert.equal(delivery.claimed,true);
    assert.equal((await claim(sms.token)).status,'in_flight');
    const begin = async (id=delivery.claim_id,token=sms.token,recipient='998901234567') => (await db.query('select begin_supplier_sms_delivery($1,$2,$3,$4) as ok',[sms.invite_id,id,token,recipient])).rows[0].ok;
    assert.equal(await begin(actor),false,'wrong claim cannot send');
    assert.equal(await begin(delivery.claim_id,'b'.repeat(48)),false,'stale token cannot send');
    assert.equal(await begin(delivery.claim_id,sms.token,'998901111111'),false,'stale recipient cannot send');
    await db.exec(`update external_suppliers set opt_out=true where id='${supplier}';`);
    assert.equal(await begin(),false,'opt-out after claim must block provider call');
    await db.exec(`update external_suppliers set opt_out=false,status='inactive' where id='${supplier}';`);
    assert.equal(await begin(),false,'deactivation after claim must block provider call');
    await db.exec(`update external_suppliers set status='registry' where id='${supplier}'; update requests set status='closed' where id='${request}';`);
    assert.equal(await begin(),false,'request closed after claim must block provider call');
    await db.exec(`update requests set status='open' where id='${request}';`);
    assert.equal(await begin(),true);
    assert.equal(await begin(),false,'same attempt cannot start twice');
    await db.query('select release_supplier_invite_delivery($1,$2)',[sms.invite_id,delivery.claim_id]);
    await db.exec(`update supplier_invites set delivery_claimed_at=now()-interval '1 day';`);
    assert.equal((await claim(sms.token)).status,'delivery_unknown');
    await assert.rejects(create('sms'),/delivery_reconciliation_required/);
    const finish = async (attempt,outcome,provider=null) => (await db.query('select finish_supplier_sms_delivery($1,$2,$3,$4) as ok',[sms.invite_id,attempt,outcome,provider])).rows[0].ok;
    assert.equal(await finish(actor,'accepted','wrong'),false);
    assert.equal(await finish(delivery.claim_id,'accepted'),false,'provider receipt required');
    assert.equal(await finish(delivery.claim_id,'rejected'),true,'verified rejection enables retry');
    delivery = await claim(sms.token);
    assert.equal(delivery.claimed,true);
    assert.equal(await begin(),true);
    assert.equal(await finish(delivery.claim_id,'accepted','provider-123'),true);
    assert.equal((await row()).provider_message_id,'provider-123');
    assert.equal((await claim(sms.token)).status,'sent');
    assert.equal(await finish(delivery.claim_id,'rejected'),false,'late result cannot undo acceptance');
    await db.exec(`update supplier_invites set sms_delivery_pending=true,status='responded';`);
    assert.equal(await finish(delivery.claim_id,'accepted','provider-123'),true);
    assert.equal((await row()).status,'responded','completion must preserve a response received during delivery');
    await db.exec(`set role authenticated;`);
    await assert.rejects(db.query('select begin_supplier_sms_delivery($1,$2,$3,$4)',[sms.invite_id,delivery.claim_id,sms.token,'998901234567']),/permission denied/);
    await assert.rejects(db.query('select finish_supplier_sms_delivery($1,$2,$3,$4)',[sms.invite_id,delivery.claim_id,'rejected',null]),/permission denied/);
    await db.exec('reset role; set role anon;');
    await assert.rejects(db.query('select claim_supplier_invite_delivery($1,$2,$3)',[sms.invite_id,actor,sms.token]),/permission denied/);
    await db.exec('reset role;');
    // Email has the same durable boundary, including reissue across channels.
    const emailMigration = fs.readdirSync('supabase/migrations').find(n => n.endsWith('_supplier_email_delivery_attempt_guard.sql'));
    const legacySupplier='00000000-0000-4000-8000-000000000004';
    await db.exec(`insert into external_suppliers(id,supplier_type,name,email,source_record_id) values('${legacySupplier}','transport','Legacy','legacy@example.com','legacy-fixture');
      insert into supplier_invites(request_id,supplier_id,created_by,channel,recipient,token_hash,status,failure_reason)
      values('${request}','${legacySupplier}','${actor}','email','legacy@example.com',repeat('f',64),'failed','resend_timeout');`);
    await db.exec(read(emailMigration));
    const legacy=(await db.query('select * from supplier_invites where supplier_id=$1',[legacySupplier])).rows[0];
    assert.equal(legacy.email_delivery_pending,true,'ambiguous legacy attempts must be quarantined');
    await assert.rejects(db.query('select create_supplier_invite($1,$2,$3)',[request,legacySupplier,'email']),/delivery_reconciliation_required/);
    assert.equal((await db.query('select finish_supplier_email_delivery($1,$2,$3,$4) as ok',[legacy.id,legacy.email_delivery_attempt_id,'rejected',null])).rows[0].ok,true);
    await db.query('delete from external_suppliers where id=$1',[legacySupplier]);
    await db.exec(`update supplier_invites set status='failed',sms_delivery_pending=false,
      delivery_claim_id=null,delivery_claimed_at=null;`);
    let email = await create('email');
    const emailClaim = async () => (await db.query('select claim_supplier_invite_delivery($1,$2,$3) as result',[email.invite_id,actor,email.token])).rows[0].result;
    let ec = await emailClaim();
    const emailBegin = async (claim=ec.claim_id,t=email.token,recipient='a@example.com') => (await db.query('select begin_supplier_email_delivery($1,$2,$3,$4) as ok',[email.invite_id,claim,t,recipient])).rows[0].ok;
    assert.equal(await emailBegin(actor),false);
    assert.equal(await emailBegin(ec.claim_id,'b'.repeat(48)),false);
    assert.equal(await emailBegin(ec.claim_id,email.token,'stale@example.com'),false);
    await db.exec(`update external_suppliers set opt_out=true where id='${supplier}';`);
    assert.equal(await emailBegin(),false);
    await db.exec(`update external_suppliers set opt_out=false,status='inactive' where id='${supplier}';`);
    assert.equal(await emailBegin(),false);
    await db.exec(`update external_suppliers set status='registry' where id='${supplier}'; update requests set status='closed';`);
    assert.equal(await emailBegin(),false);
    await db.exec(`update requests set status='open',travel_date=current_date-1;`);
    assert.equal(await emailBegin(),false,'expired open request cannot deliver');
    await db.exec(`update requests set travel_date=current_date+1;`);
    assert.equal(await emailBegin(),true);
    assert.equal(await emailBegin(),false,'one begin per attempt');
    await db.query('select release_supplier_invite_delivery($1,$2)',[email.invite_id,ec.claim_id]);
    await db.exec(`update supplier_invites set delivery_claimed_at=now()-interval '1 day';`);
    assert.equal((await emailClaim()).status,'delivery_unknown');
    await assert.rejects(create('email'),/delivery_reconciliation_required/);
    await assert.rejects(create('sms'),/delivery_reconciliation_required/);
    await db.exec(`update external_suppliers set email='corrected@example.com' where id='${supplier}';
      insert into outreach_email_suppressions(email,reason,replacement_email) values('corrected@example.com','test','replacement@example.com');`);
    assert.equal((await row()).recipient,'a@example.com','pending attempt retains its recipient snapshot');
    assert.equal((await row()).email_delivery_pending,true);
    const emailFinish = async (attempt,outcome,receipt=null) => (await db.query('select finish_supplier_email_delivery($1,$2,$3,$4) as ok',[email.invite_id,attempt,outcome,receipt])).rows[0].ok;
    assert.equal(await emailFinish(actor,'accepted','wrong'),false);
    assert.equal(await emailFinish(ec.claim_id,'accepted'),false);
    assert.equal(await emailFinish(ec.claim_id,'rejected'),true);
    assert.equal((await row()).recipient,'replacement@example.com','verified rejection applies deferred contact recovery');
    email=await create('email');ec=await emailClaim();
    assert.equal(await emailBegin(ec.claim_id,email.token,'replacement@example.com'),true);
    await db.exec(`update supplier_invites set status='responded';`);
    assert.equal(await emailFinish(ec.claim_id,'accepted','resend-123'),true);
    assert.equal((await row()).status,'responded');
    assert.equal((await row()).provider_message_id,'resend-123');
    assert.equal(await emailFinish(ec.claim_id,'rejected'),false,'late completion cannot undo accepted receipt');
    await db.exec('set role authenticated;');
    await assert.rejects(db.query('select begin_supplier_email_delivery($1,$2,$3,$4)',[email.invite_id,ec.claim_id,email.token,'replacement@example.com']),/permission denied/);
    await assert.rejects(db.query('select finish_supplier_email_delivery($1,$2,$3,$4)',[email.invite_id,ec.claim_id,'rejected',null]),/permission denied/);
    await db.exec('reset role; set role anon;');
    await assert.rejects(db.query('select finish_supplier_email_delivery($1,$2,$3,$4)',[email.invite_id,ec.claim_id,'accepted','resend-123']),/permission denied/);
    await db.exec('reset role;');
    assert(first.invite_id);
    console.log('SQL PASS: real invite RPC, legacy/current contact recovery, replacement chains, pending SMS persistence, denial rechecks, email/SMS retries and service-only reconciliation');
  } finally { await db.close(); }
})().catch(error => { console.error(error); process.exit(1); });
