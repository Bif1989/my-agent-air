create table if not exists public.billing_payment_orders (
  id uuid primary key default gen_random_uuid(),
  order_ref text not null unique default ('maa_' || replace(gen_random_uuid()::text, '-', '')),
  user_id uuid not null references public.profiles(id) on delete cascade,
  provider text not null default 'click' check (provider = 'click'),
  purpose text not null default 'subscription' check (purpose = 'subscription'),
  plan_code text not null references public.billing_subscription_plans(code),
  amount integer not null check (amount > 0),
  currency text not null default 'UZS' check (currency = 'UZS'),
  status text not null default 'pending' check (status in ('pending','prepared','paid','cancelled','expired','failed')),
  merchant_prepare_id integer generated by default as identity unique,
  click_trans_id bigint unique,
  click_paydoc_id bigint,
  subscription_id uuid references public.billing_subscriptions(id),
  provider_error integer,
  provider_error_note text,
  expires_at timestamptz not null default (now() + interval '2 hours'),
  prepared_at timestamptz,
  paid_at timestamptz,
  cancelled_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists billing_payment_orders_user_created_idx
  on public.billing_payment_orders(user_id, created_at desc);
create index if not exists billing_payment_orders_status_expires_idx
  on public.billing_payment_orders(status, expires_at);

alter table public.billing_payment_orders enable row level security;

revoke all on public.billing_payment_orders from anon;
revoke insert, update, delete on public.billing_payment_orders from authenticated;
grant select on public.billing_payment_orders to authenticated;

do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'billing_payment_orders'
      and policyname = 'billing_payment_orders_select_own'
  ) then
    create policy billing_payment_orders_select_own
      on public.billing_payment_orders
      for select to authenticated
      using ((select auth.uid()) = user_id);
  end if;
end $$;

create or replace function public.prepare_billing_click_order(
  p_order_ref text,
  p_click_trans_id bigint,
  p_click_paydoc_id bigint,
  p_amount integer
) returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_order public.billing_payment_orders%rowtype;
begin
  select * into v_order
  from public.billing_payment_orders
  where order_ref = p_order_ref and provider = 'click'
  for update;

  if v_order.id is null then
    return jsonb_build_object('ok', false, 'reason', 'order_not_found');
  end if;
  if v_order.status = 'paid' then
    return jsonb_build_object('ok', false, 'reason', 'already_paid', 'merchant_prepare_id', v_order.merchant_prepare_id);
  end if;
  if v_order.status in ('cancelled','failed','expired') then
    return jsonb_build_object('ok', false, 'reason', 'cancelled');
  end if;
  if v_order.expires_at <= now() then
    update public.billing_payment_orders
       set status = 'expired', updated_at = now()
     where id = v_order.id;
    return jsonb_build_object('ok', false, 'reason', 'expired');
  end if;
  if v_order.amount <> p_amount then
    return jsonb_build_object('ok', false, 'reason', 'amount_mismatch');
  end if;
  if v_order.click_trans_id is not null and v_order.click_trans_id <> p_click_trans_id then
    return jsonb_build_object('ok', false, 'reason', 'transaction_mismatch');
  end if;

  update public.billing_payment_orders
     set status = 'prepared',
         click_trans_id = coalesce(click_trans_id, p_click_trans_id),
         click_paydoc_id = coalesce(click_paydoc_id, p_click_paydoc_id),
         prepared_at = coalesce(prepared_at, now()),
         updated_at = now()
   where id = v_order.id;

  return jsonb_build_object(
    'ok', true,
    'merchant_prepare_id', v_order.merchant_prepare_id,
    'order_ref', v_order.order_ref
  );
end;
$$;

create or replace function public.complete_billing_click_order(
  p_order_ref text,
  p_click_trans_id bigint,
  p_click_paydoc_id bigint,
  p_merchant_prepare_id integer
) returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_order public.billing_payment_orders%rowtype;
  v_plan public.billing_subscription_plans%rowtype;
  v_subscription_id uuid;
  v_existing_end timestamptz;
  v_start timestamptz;
  v_end timestamptz;
begin
  select * into v_order
  from public.billing_payment_orders
  where order_ref = p_order_ref and provider = 'click'
  for update;

  if v_order.id is null then
    return jsonb_build_object('ok', false, 'reason', 'order_not_found');
  end if;
  if v_order.merchant_prepare_id <> p_merchant_prepare_id then
    return jsonb_build_object('ok', false, 'reason', 'prepare_mismatch');
  end if;
  if v_order.click_trans_id is not null and v_order.click_trans_id <> p_click_trans_id then
    return jsonb_build_object('ok', false, 'reason', 'transaction_mismatch');
  end if;
  if v_order.status = 'paid' then
    return jsonb_build_object(
      'ok', true,
      'already_paid', true,
      'merchant_confirm_id', v_order.merchant_prepare_id,
      'subscription_id', v_order.subscription_id
    );
  end if;
  if v_order.status not in ('pending','prepared') then
    return jsonb_build_object('ok', false, 'reason', 'cancelled');
  end if;

  select * into v_plan
  from public.billing_subscription_plans
  where code = v_order.plan_code;

  if v_plan.code is null or not v_plan.is_active or v_plan.price_amount is null then
    return jsonb_build_object('ok', false, 'reason', 'plan_unavailable');
  end if;
  if v_plan.price_amount <> v_order.amount or v_order.currency <> v_plan.currency then
    return jsonb_build_object('ok', false, 'reason', 'amount_mismatch');
  end if;

  select max(ends_at) into v_existing_end
  from public.billing_subscriptions
  where user_id = v_order.user_id
    and cancelled_at is null
    and ends_at > now();

  v_start := greatest(now(), coalesce(v_existing_end, now()));
  v_end := v_start + make_interval(days => v_plan.duration_days);

  insert into public.billing_subscriptions (
    user_id, plan_code, amount, currency, starts_at, ends_at,
    method, reference, note, recorded_by
  ) values (
    v_order.user_id, v_order.plan_code, v_order.amount, v_order.currency, v_start, v_end,
    'click', 'CLICK:' || p_click_trans_id::text || ':' || v_order.order_ref,
    'CLICK Shop API orqali avtomatik tasdiqlandi', v_order.user_id
  ) returning id into v_subscription_id;

  update public.billing_payment_orders
     set status = 'paid',
         click_trans_id = coalesce(click_trans_id, p_click_trans_id),
         click_paydoc_id = coalesce(click_paydoc_id, p_click_paydoc_id),
         subscription_id = v_subscription_id,
         paid_at = now(),
         updated_at = now()
   where id = v_order.id;

  return jsonb_build_object(
    'ok', true,
    'already_paid', false,
    'merchant_confirm_id', v_order.merchant_prepare_id,
    'subscription_id', v_subscription_id,
    'starts_at', v_start,
    'ends_at', v_end
  );
end;
$$;

create or replace function public.cancel_billing_click_order(
  p_order_ref text,
  p_click_trans_id bigint,
  p_provider_error integer,
  p_provider_error_note text
) returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_order public.billing_payment_orders%rowtype;
begin
  select * into v_order
  from public.billing_payment_orders
  where order_ref = p_order_ref and provider = 'click'
  for update;

  if v_order.id is null then
    return jsonb_build_object('ok', false, 'reason', 'order_not_found');
  end if;
  if v_order.status = 'paid' then
    return jsonb_build_object('ok', true, 'already_paid', true);
  end if;

  update public.billing_payment_orders
     set status = 'cancelled',
         click_trans_id = coalesce(click_trans_id, p_click_trans_id),
         provider_error = p_provider_error,
         provider_error_note = left(coalesce(p_provider_error_note, ''), 500),
         cancelled_at = coalesce(cancelled_at, now()),
         updated_at = now()
   where id = v_order.id;

  return jsonb_build_object('ok', true, 'cancelled', true);
end;
$$;

